import { SurveyStudy, SurveyQuestion } from "../types";

export function generateMarkdownReport(study: SurveyStudy, question: SurveyQuestion): string {
  const result = question.simulatedResult;
  const isSimulated = !!result;

  let report = `# Synthetic User Research Report: ${study.title}\n\n`;
  report += `**Date:** ${new Date().toLocaleDateString()} | **Market Panel:** ${study.market === "IN" ? "India Mass Market" : "US National Cohort"}\n\n`;
  report += `## Survey Question Tested\n`;
  report += `> "${question.questionText}"\n\n`;

  if (question.actionA || question.baselineB) {
    report += `### Choice Framing\n`;
    report += `- **Action A (Target Innovation):** ${question.actionA || "N/A"}\n`;
    report += `- **Baseline B (Status Quo Default):** ${question.baselineB || "N/A"}\n\n`;
  }

  if (isSimulated && result) {
    const adoptCount = result.personaResults.filter((p) => p.decisionStance === "YES").length;
    report += `## Panel Consensus Summary\n`;
    report += `- **Consensus Stance:** ${result.weightedScore >= 50 ? "Adopts Action A" : "Retains Status Quo (Rejects)"}\n`;
    report += `- **Post-Stratified Adoption Rate:** ${result.weightedScore}%\n`;
    report += `- **Adoption Split:** ${adoptCount} of ${result.personaResults.length} personas approved\n\n`;

    report += `## 5 MECE Persona Voice Reactions & Feedback\n\n`;
    result.personaResults.forEach((p, idx) => {
      report += `### ${idx + 1}. ${p.personaName} — *${p.personaRole}* (Weight: ${Math.round(p.weight * 100)}%)\n`;
      report += `- **Decision:** ${p.decisionStance === "YES" ? "✅ ADOPTS" : "❌ REJECTS"} (${p.targetMetricScore}% probability)\n`;
      report += `- **Verbatim Voice Quote:** "${p.responseText}"\n`;
      if (p.primaryObjection) {
        report += `- **Primary Friction / Objection:** ${p.primaryObjection}\n`;
      }
      report += `- **Dominant Bottleneck:** ${p.dominantBottleneck}\n`;
      report += `- **Friction Score:** ${p.effectiveFriction} / 10 | **Net Utility (ΔV):** ${p.deltaV >= 0 ? "+" : ""}${p.deltaV}\n\n`;
    });
  } else {
    report += `*(This question has not been simulated yet)*\n\n`;
  }

  report += `---\n*Generated by Synthetic User Simulation Engine (EB-DCA v4.0)*\n`;
  return report;
}

export function generateCsvReport(study: SurveyStudy, question: SurveyQuestion): string {
  const result = question.simulatedResult;
  if (!result) return "Question,Persona,Role,Weight,Stance,Score,Quote,Objection\n";

  const rows = [
    ["Question", "Persona Name", "Role", "Population Weight", "Decision Stance", "Adoption Probability %", "Voice Quote", "Primary Objection"],
  ];

  result.personaResults.forEach((p) => {
    rows.push([
      `"${question.questionText.replace(/"/g, '""')}"`,
      `"${p.personaName}"`,
      `"${p.personaRole}"`,
      `"${Math.round(p.weight * 100)}%"`,
      `"${p.decisionStance}"`,
      `"${p.targetMetricScore}%"`,
      `"${p.responseText.replace(/"/g, '""')}"`,
      `"${(p.primaryObjection || "").replace(/"/g, '""')}"`,
    ]);
  });

  return rows.map((r) => r.join(",")).join("\n");
}

export function downloadFile(filename: string, content: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
